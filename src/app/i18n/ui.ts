const DICTS: Record<UiLang, Dict> = { es, en, pt, it };

export function translate(lang: UiLang, key: UiKey, vars: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? es[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function useT(): (key: UiKey, vars?: Record<string, string | number>) => string {
  const lang = useStore((s) => s.uiLang);
  return (key, vars) => translate(lang, key, vars);
}

/** Nombre legible de un tipo de sección/página. */
export function sectionName(t: (k: UiKey) => string, type: string): string {
  const key = `sec.${type}` as UiKey;
  const v = t(key);
  return v === key ? type : v;
}

/** Texto de la interfaz para una clave armada en tiempo de ejecución, con respaldo si no existe. */
export function uiText(t: (k: UiKey) => string, key: string, fallback: string): string {
  const v = t(key as UiKey);
  return v === key ? fallback : v;
}

/** Título de una página para el navegador: el núcleo da títulos fijos en español para las secciones. */
export function pageTitle(t: (k: UiKey) => string, p: { type: string; title: string; group: string }): string {
  const dynamic = p.type === 'custom' || p.type === 'weekLeft' || p.type === 'weekRight' || p.type === 'daily' || p.group.startsWith('month:');
  return dynamic && p.title ? p.title : sectionName(t, p.type);
}

export const UI_LANGS: readonly UiLang[] = ['es', 'en', 'pt', 'it'];
export const UI_LANG_NAMES: Record<UiLang, string> = { es: 'Español', en: 'English', pt: 'Português', it: 'Italiano' };

export function isUiLang(l: string): l is UiLang {
  return (UI_LANGS as readonly string[]).includes(l);
}
